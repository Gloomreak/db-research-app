from __future__ import annotations

import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator

from dotenv import load_dotenv

SCHEMA_SQLITE = """
CREATE TABLE IF NOT EXISTS projects (
    id INTEGER PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER PRIMARY KEY,
    project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    status TEXT NOT NULL CHECK (status IN ('new', 'in_progress', 'completed')),
    priority INTEGER NOT NULL CHECK (priority IN (1, 2, 3)),
    created_at TEXT NOT NULL,
    due_date TEXT
);
"""

SCHEMA_POSTGRES = """
CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT,
    status TEXT NOT NULL CHECK (status IN ('new', 'in_progress', 'completed')),
    priority INTEGER NOT NULL CHECK (priority IN (1, 2, 3)),
    created_at TEXT NOT NULL,
    due_date TEXT
);
"""

RESEARCH_INDEX = "idx_tasks_project_status"

load_dotenv()


class Database:
    def __init__(self, mode: str):
        if mode not in {"postgres", "sqlite"}:
            raise ValueError(f"Unknown server database mode: {mode}")
        self.mode = mode

    def connect(self):
        if self.mode == "sqlite":
            sqlite_path = os.getenv("SQLITE_PATH", "./data/server-research.sqlite3")
            Path(sqlite_path).parent.mkdir(parents=True, exist_ok=True)
            connection = sqlite3.connect(sqlite_path, timeout=15)
            connection.row_factory = sqlite3.Row
            connection.execute("PRAGMA foreign_keys = ON")
            connection.execute("PRAGMA busy_timeout = 15000")
            return connection
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as error:
            raise RuntimeError("Install psycopg to use PostgreSQL mode.") from error
        database_url = os.getenv("DATABASE_URL")
        if not database_url:
            raise RuntimeError("DATABASE_URL is required for PostgreSQL mode.")
        return psycopg.connect(
            database_url,
            connect_timeout=5,
            row_factory=dict_row,
            options="-c statement_timeout=120000 -c lock_timeout=10000 -c idle_in_transaction_session_timeout=30000",
        )

    @contextmanager
    def connection(self) -> Iterator[Any]:
        connection = self.connect()
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def sql(self, statement: str) -> str:
        return statement.replace("?", "%s") if self.mode == "postgres" else statement

    def initialize(self) -> None:
        with self.connection() as connection:
            schema = SCHEMA_POSTGRES if self.mode == "postgres" else SCHEMA_SQLITE
            statements = [part.strip() for part in schema.split(";") if part.strip()]
            for statement in statements:
                connection.execute(statement if self.mode == "sqlite" else self.sql(statement))
            connection.commit()

    @staticmethod
    def row_dict(row: Any) -> dict[str, Any]:
        return dict(row)


DATABASES = {
    "postgres": Database("postgres"),
    "sqlite": Database("sqlite"),
}
